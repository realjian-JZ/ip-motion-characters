# ------------------------------------------------------------------ 企鹅 penguin (flippers for arms, short legs)
def penguin():
    BD, BL, BK, BKD, FT, CR = "#2E3550", "#FFFFFF", "#F2A33A", "#D9822B", "#F2A33A", "#8C93B0"
    beak_closed = f'<path d="M -18 -252 Q 0 -262 18 -252 Q 4 -232 0 -230 Q -4 -232 -18 -252 Z" fill="{BK}"/>'
    beak_open = (f'<path d="M -18 -256 Q 0 -266 18 -256 Q 0 -248 -18 -256 Z" fill="{BK}"/>'
                 f'<path d="M -14 -250 Q 0 -246 14 -250 Q 2 -226 0 -226 Q -2 -226 -14 -250 Z" fill="{BKD}"/>'
                 f'<rect x="-9" y="-252" width="18" height="10" rx="5" fill="{MOUTH_IN}"/>')
    beaks = "".join(
        f'<g data-group="mouth" data-swap="{n}"{" data-default" if n == "smile" else ""}>{beak_open if n in ("grin", "open", "wide", "o", "u") else beak_closed}</g>'
        for n in ("smile", "flat", "sad", "grin", "open", "wide", "o", "u"))
    head = f"""<g data-part="head" data-pivot="0 -214">
  <rect x="-84" y="-362" width="168" height="156" rx="70" fill="{BD}"/>
  <g data-part="hair_tuft" data-pivot="0 -360"><path d="M -6 -360 C -10 -384 8 -394 20 -386 C 8 -382 6 -372 8 -360 Z" fill="{BD}"/></g>
  <circle cx="-30" cy="-280" r="36" fill="{BL}"/><circle cx="30" cy="-280" r="36" fill="{BL}"/>
  <rect x="-58" y="-288" width="116" height="62" rx="30" fill="{BL}"/>
  {cheeks(-248, 50, 9, 0.55)}
  {eyes(-284, 30, 24, 30, (12, 16))}
  {brows(-322, 32, CR, 28, 7)}
  <g data-part="mouth" data-pivot="0 -244">{beaks}</g>
</g>"""
    flipper = lambda s, sg: f"""<g data-part="arm_{s}" data-pivot="{sg * 82} -196">
  <path d="M {sg * 78} -206 Q {sg * 112} -168 {sg * 104} -112 Q {sg * 100} -98 {sg * 92} -110 Q {sg * 80} -160 {sg * 70} -196 Z" fill="{BD}"/>
  <g data-part="fore_{s}" data-pivot="{sg * 98} -112"><rect x="{sg * 98 - 7}" y="-118" width="14" height="20" rx="7" fill="{BD}"/></g>
</g>"""
    torso = f"""<g data-part="torso" data-pivot="0 -84">
  <rect x="-86" y="-232" width="172" height="194" rx="74" fill="{BD}"/>
  <rect x="-58" y="-196" width="116" height="146" rx="52" fill="{BL}"/>
  {head}
  {flipper("l", -1)}{flipper("r", 1)}
</g>"""
    feet = "".join(f"""<g data-part="leg_{s}" data-pivot="{sg * 27} -86">
  <rect x="{sg * 27 - 12}" y="-56" width="24" height="44" rx="10" fill="{BD}"/>
  <path d="M {sg * 27 - 26} 0 L {sg * 27 - 22} -18 Q {sg * 27} -26 {sg * 27 + 22} -18 L {sg * 27 + 26} 0 Z" fill="{FT}"/>
</g>""" for s, sg in (("l", -1), ("r", 1)))
    return svg("企鹅 penguin", feet + torso)


if __name__ == "__main__":
    for cid, fn in (("panda", panda), ("monkey", monkey), ("giraffe", giraffe), ("lion", lion), ("penguin", penguin)):
        os.makedirs(os.path.join(HERE, cid), exist_ok=True)
        with open(os.path.join(HERE, cid, "character.svg"), "w", encoding="utf-8") as f:
            f.write(fn())
        print(f"characters/{cid}/character.svg")
