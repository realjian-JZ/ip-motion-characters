"""Generate the zoo series SVGs (panda, monkey, giraffe, lion, penguin) from shared pieces.

    python characters/_zoo_build.py

Same rig and part names as the human series (see references/part-card.md), so every motion template applies.
Edit the per-animal functions below and re-run; the SVGs are the output, this file is the source.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
INK = "#2B2233"
MOUTH_IN, TONGUE = "#7A2A2A", "#FF7D7D"


def mouths(dy=0, color=MOUTH_IN, stroke=6):
    """The 8 shared mouth shapes (smile flat sad grin open wide o u), shifted by dy."""
    return f"""<g transform="translate(0 {dy})">
  <g data-group="mouth" data-swap="smile" data-default=""><path d="M -18 -230 Q 0 -214 18 -230" fill="none" stroke="{color}" stroke-width="{stroke}" stroke-linecap="round"/></g>
  <g data-group="mouth" data-swap="flat"><path d="M -12 -224 L 12 -224" fill="none" stroke="{color}" stroke-width="{stroke}" stroke-linecap="round"/></g>
  <g data-group="mouth" data-swap="sad"><path d="M -15 -216 Q 0 -229 15 -216" fill="none" stroke="{color}" stroke-width="{stroke}" stroke-linecap="round"/></g>
  <g data-group="mouth" data-swap="grin"><path d="M -24 -234 L 24 -234 Q 22 -204 0 -204 Q -22 -204 -24 -234 Z" fill="{MOUTH_IN}"/><path d="M -11 -210 Q 0 -218 11 -210 Q 6 -204 0 -204 Q -6 -204 -11 -210 Z" fill="{TONGUE}"/><rect x="-17" y="-234" width="34" height="6" rx="3" fill="#FFFFFF"/></g>
  <g data-group="mouth" data-swap="open"><rect x="-12" y="-236" width="24" height="23" rx="10" fill="{MOUTH_IN}"/><rect x="-7" y="-220" width="14" height="6" rx="3" fill="{TONGUE}"/></g>
  <g data-group="mouth" data-swap="wide"><rect x="-18" y="-232" width="36" height="14" rx="7" fill="{MOUTH_IN}"/><rect x="-13" y="-232" width="26" height="5" rx="2.5" fill="#FFFFFF"/></g>
  <g data-group="mouth" data-swap="o"><rect x="-8" y="-233" width="16" height="18" rx="8" fill="{MOUTH_IN}"/></g>
  <g data-group="mouth" data-swap="u"><rect x="-6" y="-229" width="12" height="11" rx="5.5" fill="{MOUTH_IN}"/></g>
</g>"""


def eyes(cy=-276, dx=38, w=30, h=36, pupil=(14, 19), white="#FFFFFF"):
    pw, ph = pupil
    return f"""<g data-part="eyes" data-pivot="0 {cy}">
  <rect x="{-dx - w / 2}" y="{cy - h / 2}" width="{w}" height="{h}" rx="{w * 0.4:.0f}" fill="{white}"/>
  <rect x="{dx - w / 2}" y="{cy - h / 2}" width="{w}" height="{h}" rx="{w * 0.4:.0f}" fill="{white}"/>
  <g data-part="pupils" data-pivot="0 {cy}">
    <rect x="{-dx - pw / 2 + 1}" y="{cy - ph / 2 + 1}" width="{pw}" height="{ph}" rx="{pw * 0.42:.0f}" fill="{INK}"/>
    <rect x="{dx - pw / 2 + 1}" y="{cy - ph / 2 + 1}" width="{pw}" height="{ph}" rx="{pw * 0.42:.0f}" fill="{INK}"/>
    <rect x="{-dx + 2}" y="{cy - ph / 2 + 4}" width="5" height="5" rx="2.5" fill="#FFFFFF"/>
    <rect x="{dx + 2}" y="{cy - ph / 2 + 4}" width="5" height="5" rx="2.5" fill="#FFFFFF"/>
  </g>
</g>"""


def brows(cy=-312, dx=38, color=INK, w=32, h=8):
    return "".join(
        f'<g data-part="brow_{s}" data-pivot="{x} {cy}"><rect x="{x - w / 2}" y="{cy - h / 2}" width="{w}" height="{h}" rx="{h / 2}" fill="{color}"/></g>'
        for s, x in (("l", -dx), ("r", dx)))


def cheeks(cy=-236, dx=60, r=10, op=0.5):
    return f'<circle cx="{-dx}" cy="{cy}" r="{r}" fill="#FF9E9E" opacity="{op}"/><circle cx="{dx}" cy="{cy}" r="{r}" fill="#FF9E9E" opacity="{op}"/>'


def arms(x=84, fur="#000", paw="#000", upper_w=32, fore_w=28, hand=30, hand_y=-106, extra_hand=""):
    out = []
    for s, sg in (("l", -1), ("r", 1)):
        cx = sg * x
        out.append(f"""<g data-part="arm_{s}" data-pivot="{cx} -188">
  <rect x="{cx - upper_w / 2}" y="-204" width="{upper_w}" height="68" rx="{upper_w / 2}" fill="{fur}"/>
  <g data-part="fore_{s}" data-pivot="{cx} -146">
    <rect x="{cx - fore_w / 2}" y="-156" width="{fore_w}" height="54" rx="{fore_w / 2}" fill="{fur}"/>
    {extra_hand.format(cx=cx)}
    <rect x="{cx - hand / 2}" y="{hand_y}" width="{hand}" height="30" rx="14" fill="{paw}"/>
  </g>
</g>""")
    return "\n".join(out)


def legs(fur, foot, hip=27, w=36, foot_w=48, top=-96, extra=""):
    out = []
    for s, sg in (("l", -1), ("r", 1)):
        cx = sg * hip
        out.append(f"""<g data-part="leg_{s}" data-pivot="{cx} -86">
  <rect x="{cx - w / 2}" y="{top}" width="{w}" height="{-top - 14}" rx="12" fill="{fur}"/>
  <rect x="{cx - foot_w / 2 + sg * 3}" y="-24" width="{foot_w}" height="24" rx="11" fill="{foot}"/>{extra.format(cx=cx)}
</g>""")
    return "\n".join(out)


def svg(name, body):
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 600 600">
  <!-- {name} · zoo series · generated by characters/_zoo_build.py · origin = feet centre, y up is negative -->
  <g transform="translate(300 560)">
    <g data-part="shadow" data-pivot="0 0"><ellipse cx="0" cy="0" rx="86" ry="12" fill="#000" opacity="0.12"/></g>
    <g data-part="root" data-pivot="0 0">
      <g data-part="body" data-pivot="0 0">
{body}
      </g>
    </g>
  </g>
</svg>
"""


# ------------------------------------------------------------------ 熊猫 panda
def panda():
    W, B, BELLY = "#FFFFFF", INK, "#F1ECE3"
    ear = lambda s, x: f'<g data-part="ear_{s}" data-pivot="{x} -330"><circle cx="{x * 1.06:.0f}" cy="-346" r="28" fill="{B}"/><circle cx="{x * 1.06:.0f}" cy="-346" r="13" fill="#4A4058"/></g>'
    patch = lambda x, a: f'<rect x="{x - 24}" y="-304" width="48" height="58" rx="23" fill="{B}" transform="rotate({a} {x} -275)"/>'
    head = f"""<g data-part="head" data-pivot="0 -198">
  {ear("l", -66)}{ear("r", 66)}
  <rect x="-98" y="-366" width="196" height="172" rx="76" fill="{W}"/>
  {patch(-40, -18)}{patch(40, 18)}
  {cheeks(-232, 66)}
  {eyes(-276, 40, 22, 26, (11, 15))}
  {brows(-322, 40, B, 28, 7)}
  <rect x="-14" y="-252" width="28" height="16" rx="8" fill="{B}"/>
  <g data-part="mouth" data-pivot="0 -222">{mouths(2)}</g>
</g>"""
    torso = f"""<g data-part="torso" data-pivot="0 -84">
  <rect x="-92" y="-214" width="184" height="152" rx="60" fill="{W}"/>
  <rect x="-58" y="-168" width="116" height="92" rx="40" fill="{BELLY}"/>
  <rect x="-92" y="-214" width="184" height="40" rx="20" fill="{B}"/>
  {head}
  {arms(88, B, B, 36, 32, 34, -108, '<ellipse cx="{cx}" cy="-90" rx="8" ry="6" fill="#4A4058"/>')}
</g>"""
    return svg("熊猫 panda", legs(B, B, 32, 44, 54, -92) + torso)


