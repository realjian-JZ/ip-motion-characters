    ear = lambda s, x: f'<g data-part="ear_{s}" data-pivot="{x * 0.92:.0f} -284"><circle cx="{x}" cy="-284" r="27" fill="{F}"/><circle cx="{x}" cy="-284" r="15" fill="{FACE}"/></g>'
