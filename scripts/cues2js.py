"""Wrap Rhubarb Lip Sync JSON files so the pages can load them with a <script> tag.

    rhubarb -f json -o cues/line01.json line01.wav     # (Rhubarb, run separately)
    python scripts/cues2js.py                          # cues/*.json -> cues/cues.js

Then play it as motion "speak@line01" in preview / render (e.g. --motion speak@line01).
"""
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    parts = []
    for path in sorted(glob.glob(os.path.join(ROOT, "cues", "*.json"))):
        cid = os.path.splitext(os.path.basename(path))[0]
        data = json.load(open(path, encoding="utf-8"))
        parts.append(f"IPM.cues[{json.dumps(cid)}] = {json.dumps(data, ensure_ascii=False)};")
    with open(os.path.join(ROOT, "cues", "cues.js"), "w", encoding="utf-8") as f:
        f.write("// generated by scripts/cues2js.py — edit the .json files, not this\n" + "\n".join(parts) + "\n")
    print(f"cues/cues.js  {len(parts)} cue set(s)")


if __name__ == "__main__":
    main()
